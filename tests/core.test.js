"use strict";
const assert = require("node:assert/strict");
const fs = require("node:fs");
const core = require("../assets/js/core.js");
const fixture = JSON.parse(fs.readFileSync(__dirname + "/fixture.json", "utf8"));
const chapter = { id: fixture.id, title: fixture.title, path: `chapters/${fixture.id}.html`, concepts: fixture.concepts.map(c => ({ id: c.id, title: c.title })) };
core.validateCatalog({ version: 1, chapters: [chapter] });
core.validateLesson(fixture, chapter);
assert.throws(() => core.validateCatalog({ version: 1, chapters: [chapter, chapter] }));
const wrong = structuredClone(fixture); wrong.concepts[0].quiz.answer = 4;
assert.throws(() => core.validateLesson(wrong, chapter));
const wrongPrefix = structuredClone(chapter); wrongPrefix.concepts[0].id = "ch01-c01";
assert.throws(() => core.validateCatalog({ version: 1, chapters: [wrongPrefix] }));
const badDiagram = structuredClone(fixture); badDiagram.concepts[1].sections[0].blocks[1].cutoff = -1;
assert.throws(() => core.validateLesson(badDiagram, chapter));
assert.equal(core.checkNumeric("", 2, .001), null);
assert.equal(core.checkNumeric("2abc", 2, .001), null);
assert.equal(core.checkNumeric("Infinity", 2, .001), null);
assert.equal(core.checkNumeric("2e0", 2, .001), true);
assert.equal(core.checkNumeric("2.001", 2, .001), true);
assert.equal(core.checkNumeric("2.01", 2, .001), false);
assert.deepEqual(core.projectVector([2, 1, 2], [1, 0, 0]), [2, 0, 0]);
assert.deepEqual(core.planeProjections([2, 1, 2]), { XY: [2, 1, 0], XZ: [2, 0, 2], YZ: [0, 1, 2] });
assert.deepEqual(core.planeProjections([-2, 3, -4]), { XY: [-2, 3, 0], XZ: [-2, 0, -4], YZ: [0, 3, -4] });
assert.ok(core.projectSpace([1, 0, 0])[0] < 0);
assert.ok(core.projectSpace([0, 1, 0])[0] > 0);
assert.ok(core.projectSpace([0, 0, 1])[1] < 0);
assert.throws(() => core.projectVector([1, 2, 3], [0, 0, 0]));
assert.ok(Math.abs(core.bode(10, 10).magnitude + 3.0102999566) < 1e-8);
assert.equal(core.bode(10, 10).phase, -45);
assert.throws(() => core.bode(0, 10));
const memory = new Map();
const mock = { getItem: k => memory.get(k), setItem: (k, v) => memory.set(k, v), removeItem: k => memory.delete(k) };
let progress = core.storage(mock); progress.complete("ch99-c01"); progress.complete("ch99-c01");
progress.visit("ch99-c02");
progress = core.storage(mock); assert.deepEqual(progress.completed, ["ch99-c01"]);
assert.equal(progress.lastId, "ch99-c02");
assert.equal(core.resumeConcept([chapter], progress.completed, progress.lastId).concept.id, "ch99-c02");
assert.equal(core.resumeConcept([chapter], [], "removed-id").concept.id, "ch99-c01");
assert.equal(core.resumeConcept([], [], "removed-id"), null);
progress.reset(); assert.deepEqual(core.storage(mock).completed, []);
assert.equal(core.storage(mock).lastId, null);
const blocked = core.storage({ getItem() { throw Error("blocked"); } });
blocked.complete("ch99-c01"); assert.equal(blocked.available, false);
assert.deepEqual(blocked.completed, ["ch99-c01"]);
console.log("PASS: schema, numeric edge cases, Bode, vector projection, progress persistence and blocked storage");
